def preparar_numeros(lista_bruta: str) -> list:
    """
    Normaliza e deduplica a lista de números brutos.
    Garante o código de país +55 obrigatório para o WhatsApp Web.
    """
    numeros_limpos = []
    for linha in lista_bruta.strip().split('\n'):
        num = ''.join(filter(str.isdigit, linha))
        if len(num) >= 10:
            if len(num) in (10, 11) and not num.startswith('55'):
                num = '55' + num
            if num not in numeros_limpos:
                numeros_limpos.append(num)
    
    # Inverte a lista para começar de baixo para cima conforme solicitado pelo usuário
    return numeros_limpos[::-1]
